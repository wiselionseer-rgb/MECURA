export function formatSouCannabisStandardOutput(product: SouCannabisProduct): string {
  const lines = [
    `• PRODUTO: ${product.name}`,
    `• CATEGORIA / LINHA: ${product.type} (${product.colorLine ? `Linha ${product.colorLine}` : 'SouCannabis'})`,
    `• PROPORÇÃO: ${product.ratio || 'Padronizada'}`,
    `• CONCENTRAÇÃO: ${product.concentration}`,
    `• APRESENTAÇÃO: ${product.pharmaceuticalForm} — Quantidade: ${product.quantity}`,
    `• VIA DE ADMINISTRAÇÃO: ${product.administrationRoute}`
  ];

  if (product.mgPerDropTHC !== undefined || product.mgPerDropCBD !== undefined) {
    lines.push(`• CONCENTRAÇÃO POR GOTA (~26 gotas/mL): ${product.mgPerDropTHC !== undefined ? `${product.mgPerDropTHC} mg THC` : ''}${product.mgPerDropTHC !== undefined && product.mgPerDropCBD !== undefined ? ' + ' : ''}${product.mgPerDropCBD !== undefined ? `${product.mgPerDropCBD} mg CBD` : ''}`);
  }

  if (product.carrierVehicle) {
    lines.push(`• CARREADOR / VEÍCULO: ${product.carrierVehicle}`);
  }

  if (product.priceBRL !== undefined) {
    lines.push(`• VALOR ASSOCIATIVO: R$ ${product.priceBRL.toFixed(2).replace('.', ',')}`);
  }

  lines.push(`• CONTROLE ANALÍTICO: Análise laboratorial por HPLC em parceria universitária`);
  lines.push(`• INDICAÇÕES: ${product.indications || product.description}`);
  lines.push(`• EXEMPLO DE PRESCRIÇÃO: ${product.prescriptionExample || 'Conforme plano terapêutico médico individualizado.'}`);
  lines.push(`• MODO DE USO: ${product.usageInstructions || 'Uso sob orientação médica.'}`);
  lines.push(`• ORIGEM: Associação Nacional Brasileira (SouCannabis — Nacional)`);

  return lines.join('\n');
}
